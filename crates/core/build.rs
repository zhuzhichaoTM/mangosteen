//! 构建脚本：扫描 `src/template/*.rs`（排除 mod.rs），自动生成聚合文件。
//!
//! 新增模型 = 新建 `template/<model_id>.rs`（含 MODEL_ID/SLOT/DISPLAY/TEMPLATE/HASHES 常量），
//! 本脚本自动发现并在编译期生成 `pub mod` 声明 + BUILTIN_TEMPLATES/MODEL_HASHES 聚合数组。
//! mod.rs 零改动——`include!` 引入生成文件即可。

use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let template_dir = Path::new("src/template");
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR not set");
    let dest = Path::new(&out_dir).join("models.rs");

    println!("cargo:rerun-if-changed=src/template");

    let mut mods = Vec::new();
    let mut entries = Vec::new();
    let mut hash_entries = Vec::new();

    if let Ok(rd) = fs::read_dir(template_dir) {
        let mut files: Vec<_> = rd
            .flatten()
            .filter(|e| {
                e.path().extension().map_or(false, |ext| ext == "rs")
                    && e.path().file_name().map_or(false, |n| n != "mod.rs")
            })
            .collect();
        // 按文件名排序，保证生成内容稳定（避免 build 不确定性）
        files.sort_by_key(|e| e.file_name());

        for entry in files {
            let name = entry
                .path()
                .file_stem()
                .unwrap()
                .to_str()
                .unwrap()
                .to_string();
            // #[path] 用绝对路径让 Rust 从 src/template/ 加载（OUT_DIR 相对路径不可达）
            let abs = std::fs::canonicalize(&entry.path()).unwrap_or_else(|_| entry.path());
            mods.push(format!(
                "#[path = {:?}]\npub mod {name};",
                abs.to_str().unwrap_or("")
            ));
            entries.push(format!(
                "    ({name}::MODEL_ID, {name}::SLOT, {name}::DISPLAY, {name}::TEMPLATE),"
            ));
            hash_entries.push(format!("    ({name}::MODEL_ID, {name}::HASHES),"));
        }
    }

    let content = format!(
        "// @generated by build.rs — 扫描 src/template/*.rs 自动聚合，请勿手工编辑。\n\
         // 新增模型：新建 template/<model>.rs（含 MODEL_ID/SLOT/DISPLAY/TEMPLATE/HASHES），cargo 自动发现。\n\
         \n\
         {}\n\
         \n\
         /// 内置模板索引：(模型ID, 槽位, 显示名, 模板正文)。\n\
         pub const BUILTIN_TEMPLATES: &[(&str, &str, &str, &str)] = &[\n{}\n];\n\
         \n\
         /// 各模型哈希表聚合：(模型ID, &[(文件名小写, SHA256)])。\n\
         pub static MODEL_HASHES: &[(&str, &[(&str, &str)])] = &[\n{}\n];\n",
        mods.join("\n"),
        entries.join("\n"),
        hash_entries.join("\n"),
    );

    fs::write(dest, content).expect("failed to write models.rs");
}